    case FM1_WL30_HOST_04 - FM1_WL30_HOST_BASE:
    case FM1_WL30_HOST_10 - FM1_WL30_HOST_BASE:
    case FM1_WL30_HOST_14 - FM1_WL30_HOST_BASE:
    case FM1_WL30_HOST_18 - FM1_WL30_HOST_BASE:

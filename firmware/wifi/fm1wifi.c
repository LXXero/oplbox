/* Where the code runs (docs/WIFI_STAGE3.md "What runs from RAM"; felucca's app.ld copies .ram_code* into RAM):
 *  - TRIMFN, section .ram_code.fm1wifi: the trim and everything it calls, which must not touch the flash at all
 *    (tools/build.py checks this section refers to nothing outside RAM); FM1WIFI_RAMDATA what it reads;
 *  - RAMFN, .ram_code.fm1wifi_init: the rest of the radio's bring-up, in RAM only because it calls the above;
 *  - the rest (stage 2, the public functions) in the flash.
 * On the FM-1 RAM code (0x01C0xxxx) is beyond the direct call range of the flash's code (0x0200xxxx), so a call
 * across goes through a pointer the compiler cannot fold back into a direct call: FAR(fn). The linker refuses a
 * direct call across in either direction, so a missing FAR cannot get into a build. */
#define TRIMFN __attribute__((section(".ram_code.fm1wifi")))
#define RAMFN __attribute__((section(".ram_code.fm1wifi_init")))
#define FM1WIFI_RAMDATA __attribute__((section(".ram_code.fm1wifi_data")))
static inline __attribute__((always_inline)) void *far_(void *p) { void *volatile q = p; return q; }
#define FAR(fn) ((__typeof__(&fn))far_((void *)&fn))
#include "fm1wifi_tables.h"

const char *fm1wifi_strerror(int err)
{
    switch (err) {
    case FM1WIFI_OK: return "OK";
    case FM1WIFI_ENOTYET: return "NOT YET";
    case FM1WIFI_ERANGE: return "RANGE";
    case FM1WIFI_EBUS: return "NO ANSWER";
    case FM1WIFI_ETIMEOUT: return "TIMEOUT";
    case FM1WIFI_ESTATE: return "OFF";
    case FM1WIFI_EFRAME: return "BAD FRAME";
    default: return "?";
    }
}


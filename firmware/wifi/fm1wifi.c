{
    if (!radio) return FM1WIFI_ESTATE;
    if (ch < 1u || ch > 13u) return FM1WIFI_ERANGE;
    e3 = 0;
    fld(FM1_WF_CON(7), 0, 8, ch + 101u);
    return FM1WIFI_OK;
}


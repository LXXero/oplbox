#!/usr/bin/env python3
"""songs.h: every .CMF concatenated as one const array, plus a table of titles. usage: gen_songs.py out.h"""
import sys, pathlib
SA = pathlib.Path('../../stoneage/stone-age'); SF = pathlib.Path('../../soundfx/SOUNDFX/SONGS')
LIST = [  # (file, title (FONT_L: capitals, digits, signs), composer / game)
 (SA/'1STARDUS.CMF', "STARDUST FALLING",  "T.DETERT  STONE AGE 1992"),
 (SA/'2BONESTO.CMF', "BONE AND STONE",    "T.DETERT  STONE AGE 1992"),
 (SA/'3PLASTIC.CMF', "PLASTIC AGE",       "T.DETERT  STONE AGE 1992"),
 (SA/'4AUSTORM.CMF', "AUTUMN STORM",      "T.DETERT  STONE AGE 1992"),
 (SA/'5DR_TALE.CMF', "THE DRAGON'S TALE", "T.DETERT  STONE AGE 1992"),
 (SA/'6NO_CHOI.CMF', "NO CHOICE LEFT",    "T.DETERT  STONE AGE 1992"),
 (SA/'7WILDLIF.CMF', "WILDLIFE",          "T.DETERT  STONE AGE 1992"),
 (SA/'8GOLDVAL.CMF', "THE GOLDEN VALLEY", "T.DETERT  STONE AGE 1992"),
 (SF/'TRADINTR.CMF', "TRADERS INTRO",     "M.TSCHOEGL  LINEL 1991"),
 (SF/'TRADMENU.CMF', "TRADERS MENU",      "M.TSCHOEGL  LINEL 1991"),
 (SF/'TRAD_END.CMF', "TRADERS END",       "M.TSCHOEGL  LINEL 1991"),
 (SF/'NECRONOM.CMF', "NECRONOM",          "M.TSCHOEGL  LINEL 1991"),
 (SF/'TNS_END.CMF',  "NEVERENDING STORY II", "M.TSCHOEGL  LINEL 1990"),
 (SF/'KAISER.CMF',   "KAISER",            "M.TSCHOEGL  LINEL"),
 (SF/'CRYSTAL.CMF',  "CRYSTAL",           "M.TSCHOEGL  LINEL 1991"),
 (SF/'ECHOS.CMF',    "ECHOS",             "M.TSCHOEGL  LINEL 1992"),
 (SF/'DONTNOW.CMF',  "DONTNOW",           "M.TSCHOEGL  LINEL 1991"),
 (SF/'QUITE.CMF',    "QUITE",             "M.TSCHOEGL  LINEL 1991"),
]
out = ["/* generated by gen_songs.py: the SoundFX Macs Opera songs, in flash as they are on disk */",
       "#include <stdint.h>", "typedef struct { const char *title, *by, *file; uint32_t off, len; } song_t;"]
blob = bytearray(); tab = []
for f, title, by in LIST:
    d = f.read_bytes(); assert d[:4] == b'A.H.', f
    tab.append(f'    {{ "{title}", "{by}", "{f.name}", {len(blob)}u, {len(d)}u }},')
    blob += d
    while len(blob) % 4: blob.append(0)
out.append(f"#define N_SONGS {len(LIST)}u")
out.append("static const song_t SONGS[N_SONGS] = {"); out += tab; out.append("};")
out.append(f"static const uint8_t SONG_DATA[{len(blob)}u] __attribute__((aligned(4))) = {{")
for i in range(0, len(blob), 24):
    out.append("    " + ",".join(f"{b:3d}" for b in blob[i:i+24]) + ",")
out.append("};")
pathlib.Path(sys.argv[1]).write_text("\n".join(out) + "\n")
print(f"{len(LIST)} songs, {len(blob)} bytes -> {sys.argv[1]}")

/* Generates dbopl2_tables.h: every table DOSBox's dbopl computes with floating point, for the
 * chip's native rate (49716 Hz), as decimal integer initialisers. The firmware has no float
 * support, so it carries the results instead of the formulas.
 *   cc -O1 -w -o build/dbopl_gen host/dbopl_gen.c -lm && build/dbopl_gen > ../oplbox-fw/firmware/src/dbopl2_tables.h */
#include "../../cd-old/opl/dbopl.c"      /* DOSBox r3635 via Chocolate Doom 2.2.1, GPL-2+ */

static void dump_u(const char *type, const char *name, const char *attr, const void *p, int n, int width)
{
    int i;
    printf("static %s %s[%d]%s = {", type, name, n, attr);
    for (i = 0; i < n; i++) {
        long v = width == 1 ? ((const uint8_t *)p)[i] : width == 2 ? ((const uint16_t *)p)[i] : (long)((const uint32_t *)p)[i];
        printf("%s%ld%s", i % 12 ? " " : "\n    ", v, i + 1 < n ? "," : "");
    }
    printf("\n};\n");
}

static void dump_s16(const char *name, const char *attr, const int16_t *p, int n)
{
    int i;
    printf("static int16_t %s[%d]%s = {", name, n, attr);
    for (i = 0; i < n; i++)
        printf("%s%d%s", i % 12 ? " " : "\n    ", p[i], i + 1 < n ? "," : "");
    printf("\n};\n");
}

int main(void)
{
    Chip chip;
    const uint32_t rate = 49716;
    DBOPL_InitTables();
    memset(&chip, 0, sizeof chip);
    Chip__Setup(&chip, rate);
    printf("/* Generated by host/dbopl_gen.c from DOSBox dbopl (r3635) for %u Hz: do not edit.\n"
           " * WAVE_TABLEMUL, WAVE_BITS 10, RATE_SH 24, ENV_BITS 9. */\n", rate);
    printf("#define DBOPL2_RATE %uu\n#define DBOPL2_NOISE_ADD %uu\n#define DBOPL2_LFO_ADD %uu\n",
           rate, chip.noiseAdd, chip.lfoAdd);
    dump_u("const uint32_t", "FreqMul", "", chip.freqMul, 16, 4);
    dump_u("const uint32_t", "LinearRates", "", chip.linearRates, 76, 4);
    dump_u("const uint32_t", "AttackRates", "", chip.attackRates, 76, 4);
    dump_u("uint8_t", "KslTable", " DBOPL2_RAMDATA", KslTable, 128, 1);
    dump_u("uint8_t", "TremoloTable", " DBOPL2_RAMDATA", TremoloTable, TREMOLO_TABLE, 1);
    dump_u("uint16_t", "MulTable", " DBOPL2_RAMDATA", MulTable, 384, 2);
    dump_s16("WaveTable", " DBOPL2_RAMDATA", WaveTable, 8 * 512);
    return 0;
}
